import fs from 'node:fs';
import vm from 'node:vm';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'dist/data.json'), 'utf8'));
let code = fs.readFileSync(path.join(root, 'dist/app.js'), 'utf8');
const fetchIndex = code.lastIndexOf("fetch('data.json')");
if (fetchIndex < 0) throw new Error('Cannot isolate dashboard functions');
code = code.slice(0, fetchIndex);
const filters = { search: { value: '' }, category: { value: '' }, brand: { value: '' } };
const ctx = { document: { querySelector: s => filters[s.slice(1)] }, fixture: data, console };
vm.createContext(ctx);
vm.runInContext(code + `
DATA = fixture;
const check = (ok, message) => { if (!ok) throw new Error(message); };
let ps=selection(), rs=feedback(ps), s=stats(rs);
check(ps.length===12, 'Expected 12 synthetic product cards');
check(new Set(ps.map(p=>p.brand)).size===3, 'Expected 3 synthetic brands');
check(rs.length===11 && s.n===8, 'Expected 8 synthetic reviews and 3 Q&A rows');
check(s.s===2 && s.repeat===1 && s.intent===1 && s.brand===0, 'Affinity evidence mismatch');

check(DATA.feedback.every(r=>byId(r.product)), 'Unmatched feedback product ID');
check(stats(feedback([byId('demo-1')])).mean===4.5, 'Synthetic mean rating');
check(stats(feedback([byId('demo-4')])).rate===0, 'Collected reviews without signals should be zero');
check(stats(feedback([byId('demo-12')])).rate===null, 'Missing feedback should be null');
check(stats(rs).issues.filter(r=>r.rating===5).length===0, 'Five-star improvement count');
document.querySelector('#category').value='주방·식기';
check(selection().length===4, 'Category filter mismatch');
check(stats(feedback(selection())).rate===1/2, 'Category ratio must use summed review counts');
document.querySelector('#category').value='';
document.querySelector('#brand').value='샘플 의류';
check(selection().length===4 && stats(feedback(selection())).n===4, 'Brand filter and review join');
document.querySelector('#brand').value='';
document.querySelector('#search').value='zzz-no-match';
check(selection().length===0 && stats(feedback(selection())).rate===null, 'Empty search result');
document.querySelector('#search').value='';
check(overview(ps,rs).includes('48,500원'), 'Median price');
check(productView(ps).includes('상품 목록'), 'Product view');
check(feedbackView(ps,rs).includes('고객 의견'), 'Feedback view');
check(affinity(ps,rs).includes('25.0%'), 'Affinity view');
check(method().includes('플랫폼'), 'Method view');
console.log('PASS: counts, mappings, ratings, evidence, zero vs missing, filters, ratios, view rendering');
`, ctx);
